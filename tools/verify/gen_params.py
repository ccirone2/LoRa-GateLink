#!/usr/bin/env python3
"""Writes the PARAMS table (firmware/GateLink/config.cpp) as an X-macro header for the model checker.

    python3 tools/verify/gen_params.py [--fw DIR] OUT.h

ESBMC can't follow a pointer to member read from a table (`cfg.*(p->field)`, "pointer-to-member: constant propagation
failed"), so the harnesses reach each setting by name instead: `PARAM(id, field, min, max, flags)` per row, in table
order. Generated at every build, so it can't fall out of step with the firmware.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ROW = re.compile(r'\{\s*(\d+),\s*"(\w+)",\s*&Config::(\w+),\s*(-?\d+),\s*(-?\d+),\s*([\w| ]+)\s*\}')


def rows(text):
    table = text[text.index("const ParamDef PARAMS[] = {"):]
    table = table[:table.index("};")]
    out = [m.groups() for m in ROW.finditer(table)]
    if not out:
        raise SystemExit("no PARAMS rows found in config.cpp")
    for pid, name, field, *_ in out:
        if name != field:
            raise SystemExit(f"PARAMS row {pid}: name {name} isn't its field {field}")
    return out


def main(argv):
    fw = ROOT / "firmware/GateLink"
    if len(argv) == 4 and argv[1] == "--fw":
        fw, argv = Path(argv[2]), [argv[0], argv[3]]
    if len(argv) != 2:
        raise SystemExit(__doc__)
    text = (fw / "config.cpp").read_text(encoding="utf-8")
    lines = ["// Generated by tools/verify/gen_params.py from firmware/GateLink/config.cpp's PARAMS. Don't edit.",
             "#define PARAMS_TABLE(PARAM) \\"]
    lines += [f"  PARAM({pid}, {field}, {lo}, {hi}, {flags.strip()}) \\" for pid, _, field, lo, hi, flags in rows(text)]
    lines.append("")
    for pid, _, field, lo, hi, _ in rows(text):
        lines += [f"#define PARAM_ID_{field} {pid}", f"#define PARAM_MIN_{field} ({lo})", f"#define PARAM_MAX_{field} ({hi})"]
    Path(argv[1]).write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main(sys.argv)
